function M.IsEnglish()return require("aom_common").LANGUAGE=="en" end
function M.Text(key,...)
    local text=M.IsEnglish() and (EN[key] or key) or key
    if select("#",...)>0 then return string.format(text,...) end
    return text
end
function M.Separator()return M.IsEnglish() and ", " or "、" end
