#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 Windows 上生成的 Driver-Results.zip 接进 Mod 运行目录。

用法：
    python tools/apply_driver_results.py [Driver-Results.zip]

做法：先按 Windows 收集脚本的同一套标准校验压缩包（ZIP CRC、BILD/ANIM/KTEX
签名、bank/build 名称、原版骑乘所需动画），全部通过后才写入
mod/Tractor/anim/aom_tractor_driver.zip、启用清单和构建报告。
校验不通过时不动任何现有文件。
"""
import argparse
import io
import json
import os
import re
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from driver_animation import BANK, build_symbols, name_hash, parse_anim  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / 'mod' / 'Tractor'
REQUIRED_ANIMATIONS = {'mount', 'dismount', 'idle_loop', 'run_pre', 'run_loop', 'run_pst'}
REQUIRED_ENTRIES = ('anim/aom_tractor_driver.zip',
                    'scripts/aom_driver_visual_bank.lua',
                    'Driver-Build-Report.json')


def fail(message):
    raise SystemExit('ERROR: ' + message)


def check_outer(archive):
    bad = archive.testzip()
    if bad is not None:
        fail('Driver-Results.zip 内文件 CRC 校验失败：' + bad)
    names = set(archive.namelist())
    missing = [name for name in REQUIRED_ENTRIES if name not in names]
    if missing:
        fail('Driver-Results.zip 缺少：' + ', '.join(missing))
    manifest = archive.read('scripts/aom_driver_visual_bank.lua').decode('utf-8')
    if not re.search(r'available\s*=\s*true', manifest):
        fail('驾驶室构建未启用（available 不是 true），请先看构建日志')
    for key, expected in (('bank', BANK), ('build', 'aom_tractor_cabin')):
        if not re.search(r'%s\s*=\s*"%s"' % (key, re.escape(expected)), manifest):
            fail('启用清单内容异常：' + manifest.strip())
    try:
        report = json.loads(archive.read('Driver-Build-Report.json').decode('utf-8'))
    except ValueError as exc:
        fail('Driver-Build-Report.json 不是合法 JSON：%s' % exc)
    return archive.read('anim/aom_tractor_driver.zip'), manifest, report


def check_driver_bank(blob):
    with zipfile.ZipFile(io.BytesIO(blob)) as archive:
        bad = archive.testzip()
        if bad is not None:
            fail('驾驶动画包 CRC 校验失败：' + bad)
        for name, signature in (('build.bin', b'BILD'), ('anim.bin', b'ANIM')):
            data = archive.read(name)
            if data[:4] != signature:
                fail('驾驶动画包 %s 不是 %s 格式' % (name, signature.decode()))
        build, symbols = build_symbols(archive.read('build.bin'))
        if build != 'aom_tractor_cabin':
            fail('驾驶室 build 名称不匹配：' + build)
        for symbol in ('aom_cabin_back', 'aom_cabin_front',
                       'aom_driver_attachment_rear', 'aom_driver_attachment_front'):
            if name_hash(symbol) not in symbols:
                fail('驾驶室缺少符号：' + symbol)
        bank = parse_anim(archive.read('anim.bin'))
        hashes = {a['bank'] for a in bank['animations']}
        if hashes != {name_hash(BANK)}:
            fail('动画 bank 名称与 %s 不匹配' % BANK)
        names = {a['name'] for a in bank['animations']}
        missing = sorted(REQUIRED_ANIMATIONS - names)
        if missing:
            fail('缺少原版骑乘所需动画：' + ', '.join(missing))
        if not any(n.lower().endswith('.tex') and archive.read(n)[:4] == b'KTEX'
                   for n in archive.namelist()):
            fail('驾驶室图集缺失或不是 KTEX')
        return len(bank['animations']), len(symbols), names


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('results', nargs='?', default=str(ROOT / 'Driver-Results.zip'))
    parser.add_argument('--mod', default=str(MOD))
    args = parser.parse_args()

    results = Path(args.results)
    mod = Path(args.mod)
    if not results.is_file():
        fail('找不到 %s' % results)
    with zipfile.ZipFile(results) as archive:
        blob, manifest, report = check_outer(archive)
    animations, symbols, names = check_driver_bank(blob)

    target = mod / 'anim' / 'aom_tractor_driver.zip'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(blob)
    (mod / 'scripts' / 'aom_driver_visual_bank.lua').write_text(
        '-- Generated by the Windows driver builder.\n' + manifest.strip() + '\n',
        encoding='utf-8', newline='\n')
    (mod / 'Driver-Build-Report.json').write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + '\n',
        encoding='utf-8', newline='\n')

    print('已接入 %s' % target.relative_to(ROOT).as_posix())
    print('  驾驶动画 %d 个（%s 等 %d 个原版动作），build 符号 %d 个，%.1f MiB'
          % (animations, 'mount', len(REQUIRED_ANIMATIONS), symbols,
             target.stat().st_size / 1024.0 / 1024.0))
    print('  启用清单：' + manifest.strip().splitlines()[-1])
    hidden = report.get('frames_without_driver') or []
    if hidden:
        print('  提示：%d 个原版状态帧没有人物层（沿用原版坐姿合成规则）：%s'
              % (len(hidden), ', '.join(hidden)))
    print('下一步：python tools/selfcheck.py，然后安装到游戏并重启客户端/服务器。')


if __name__ == '__main__':
    main()
