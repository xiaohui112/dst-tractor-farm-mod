#!/usr/bin/env python3
"""Generate/check the build fingerprint recorded by in-game planning logs."""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SCRIPTS=ROOT/'mod/Tractor/scripts'
NAMES=sorted({p.name for p in SCRIPTS.glob('aom_seed_*.lua')}|{'aom_farm_grid.lua','aom_farm_work.lua','aom_farm_neighbors.lua','aom_dynamic_farm.lua','aom_plan_timing.lua','aom_auto_seeding.lua','aom_farm_registry.lua','aom_template_preview.lua','aom_block_plan.lua','aom_drive.lua'})
def content():
 files={name:hashlib.sha256((SCRIPTS/name).read_bytes()).hexdigest()for name in NAMES}
 digest=hashlib.sha256(json.dumps(files,sort_keys=True,separators=(',',':')).encode()).hexdigest()
 return '-- Generated by tools/planner_fingerprint.py; check before packaging.\nreturn {fingerprint="'+digest+'"}\n'
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 target=SCRIPTS/'aom_planner_build.lua';expected=content()
 if args.check:
  if not target.exists()or target.read_text()!=expected:raise SystemExit('Planning fingerprint is stale; run tools/planner_fingerprint.py')
 else:target.write_text(expected)
 print('Planning source fingerprint verified'if args.check else 'Planning source fingerprint updated')
if __name__=='__main__':main()
